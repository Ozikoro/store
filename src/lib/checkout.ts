/**
 * Checkout: from a cart to a confirmed, paid order.
 *
 * The sequence is fixed and the failure behaviour at each step is deliberate:
 *
 *   1. Re-price the cart from the catalogue. Never trust a submitted total.
 *   2. Validate the delivery address and find a shipping rate. No rate, no sale.
 *   3. Re-check stock, then create a PENDING order and reserve the stock.
 *   4. Re-validate the discount code (it may have expired since it was typed).
 *   5. Initialise the payment with the amount from step 1.
 *
 * If step 5 fails, the pending order is cancelled and the stock returns to the
 * shelf, because a customer staring at "could not reach the payment provider"
 * must be able to try again immediately.
 *
 * Confirmation is a separate path, entered only by the callback page and the
 * webhook, and both of them verify the transaction with Paystack before calling
 * `settlePayment` — which is the only function that can mark an order paid.
 */

